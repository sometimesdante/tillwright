-- Tillwright database schema.
--
-- Everything lives in the tillwright schema and the tillwright storage bucket,
-- so this app can share a Supabase project with other apps. Nothing here
-- creates, changes or drops anything in the public schema, and the auth
-- trigger only acts on sign-ups made by this app.
--
-- Safe to run more than once: it creates what is missing and replaces
-- functions, triggers and policies. It never drops tables or data.
--
-- After the first run, add tillwright to Project Settings > Data API >
-- Exposed schemas, or the Supabase API can't see these tables.
--
-- Apply it either way:
--   - paste it into the Supabase SQL Editor and run it, or
--   - set SUPABASE_DB_URL in .env.local and run `npm run seed`.
--
-- Column types are inferred from what the app reads and writes. See
-- "Database schema" in README.md, including the RLS caveats.

begin;

create schema if not exists tillwright;

-- Tables ------------------------------------------------------------------

create table if not exists tillwright.products (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text not null,
  category    text,
  description text,
  image_url   text,
  purchase    numeric,
  mrp         numeric,
  pretax      numeric,
  tax         numeric,
  price       numeric not null,
  inventory   integer default 0
);
-- Projects created before descriptions were added.
alter table tillwright.products add column if not exists description text;

create table if not exists tillwright.transactions (
  id               bigint generated by default as identity primary key,
  created_at       timestamptz not null default now(),
  invoice_id       integer unique,
  transaction_id   text not null,
  razorpay_id      text,
  name             text,
  email            text,
  phone            text,
  address          text,
  payment_status   text not null,
  delivery_status  text not null default 'pending',
  amount           numeric not null,
  products         jsonb not null default '[]'::jsonb
);
-- True once this order has taken its items out of stock, so cancelling it
-- knows whether to put them back.
alter table tillwright.transactions
  add column if not exists stock_reserved boolean not null default false;
create index if not exists transactions_transaction_id_idx on tillwright.transactions (transaction_id);
create index if not exists transactions_email_idx on tillwright.transactions (email);

-- id is not used by the code; it ties each profile to its auth user.
create table if not exists tillwright.profiles (
  id     uuid primary key references auth.users (id) on delete cascade,
  email  text not null unique,
  role   text not null default 'customer'
);

create table if not exists tillwright.guest_profiles (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text,
  email       text,
  phone       text,
  address     text,
  role        text default 'guest'
);

-- Create a profile row for every sign-up made by this app. The app passes
-- user metadata {"app": "tillwright"} on sign-up; users created by other apps
-- sharing this project don't fire the trigger.
create or replace function tillwright.handle_new_user()
returns trigger language plpgsql security definer set search_path = tillwright as $$
begin
  insert into tillwright.profiles (id, email) values (new.id, new.email)
  on conflict (email) do nothing;
  return new;
end;
$$;

drop trigger if exists tillwright_on_auth_user_created on auth.users;
create trigger tillwright_on_auth_user_created
  after insert on auth.users
  for each row
  when (new.raw_user_meta_data ->> 'app' = 'tillwright')
  execute function tillwright.handle_new_user();

-- Admin helper, mirroring the app's check (profiles.role = 'admin' by email).
create or replace function tillwright.is_admin()
returns boolean language sql stable security definer set search_path = tillwright as $$
  select exists (
    select 1 from tillwright.profiles
    where email = auth.jwt() ->> 'email' and role = 'admin'
  );
$$;

-- Invoice numbers --------------------------------------------------------
-- One gap-free series for GST, handed out by the database so two orders
-- placed at the same moment can't get the same number. The app shows them
-- as INV-<year>-<0000> (src/utils/formatInvoiceNo.ts).

create sequence if not exists tillwright.invoice_number_seq;

-- Keep the sequence ahead of numbers already in use (safe to re-run).
select setval(
  'tillwright.invoice_number_seq',
  greatest(coalesce((select max(invoice_id) from tillwright.transactions), 0), 1),
  coalesce((select max(invoice_id) from tillwright.transactions), 0) > 0
);

-- Gives an order its invoice number once; later calls return the same one.
create or replace function tillwright.assign_invoice_number(order_id bigint)
returns integer language plpgsql security definer set search_path = tillwright as $$
declare
  assigned integer;
begin
  update transactions
     set invoice_id = nextval('invoice_number_seq')
   where id = order_id and invoice_id is null
  returning invoice_id into assigned;

  if assigned is null then
    select invoice_id into assigned from transactions where id = order_id;
  end if;
  return assigned;
end;
$$;

-- Stock -------------------------------------------------------------------
-- items is a JSON array of {"id": <product id>, "count": <quantity>}.

-- Takes items out of stock only if every one of them is available. Locks the
-- product rows first, so two checkouts can't both buy the last unit.
create or replace function tillwright.reserve_stock(items jsonb)
returns boolean language plpgsql security definer set search_path = tillwright as $$
declare
  item jsonb;
  available integer;
begin
  perform 1 from products
   where id in (select (value ->> 'id')::bigint from jsonb_array_elements(items))
   order by id
     for update;

  for item in select value from jsonb_array_elements(items) loop
    select inventory into available from products where id = (item ->> 'id')::bigint;
    if available is null or available < (item ->> 'count')::integer then
      return false;
    end if;
  end loop;

  update products p
     set inventory = p.inventory - (i.value ->> 'count')::integer
    from jsonb_array_elements(items) i
   where p.id = (i.value ->> 'id')::bigint;
  return true;
end;
$$;

-- Moves stock without checking: direction -1 takes items (an online payment
-- that already went through), +1 puts them back (a cancelled order).
-- Inventory never drops below zero.
create or replace function tillwright.adjust_stock(items jsonb, direction integer)
returns void language sql security definer set search_path = tillwright as $$
  update products p
     set inventory = greatest(coalesce(p.inventory, 0) + direction * (i.value ->> 'count')::integer, 0)
    from jsonb_array_elements(items) i
   where p.id = (i.value ->> 'id')::bigint;
$$;

-- Only the server (service role) may call these.
revoke all on function tillwright.assign_invoice_number(bigint) from public, anon, authenticated;
revoke all on function tillwright.reserve_stock(jsonb) from public, anon, authenticated;
revoke all on function tillwright.adjust_stock(jsonb, integer) from public, anon, authenticated;
grant execute on function tillwright.assign_invoice_number(bigint) to service_role;
grant execute on function tillwright.reserve_stock(jsonb) to service_role;
grant execute on function tillwright.adjust_stock(jsonb, integer) to service_role;

-- Only the RLS policies (as the signed-in user) and the server use is_admin().
revoke all on function tillwright.is_admin() from public, anon;
grant execute on function tillwright.is_admin() to authenticated, service_role;
-- A trigger function; nobody calls it directly.
revoke all on function tillwright.handle_new_user() from public, anon, authenticated;

-- Privileges ---------------------------------------------------------------
-- A new schema grants nothing to the Supabase API roles, so grant exactly
-- what the policies below allow. RLS still decides which rows each role sees.

grant usage on schema tillwright to anon, authenticated, service_role;

grant select on tillwright.products to anon;
grant select, insert, update on tillwright.products to authenticated;
grant select, update on tillwright.transactions to authenticated;
grant select on tillwright.profiles to authenticated;
grant select on tillwright.guest_profiles to authenticated;

-- The server (service role) reads and writes everything.
grant all on all tables in schema tillwright to service_role;
grant all on all sequences in schema tillwright to service_role;
alter default privileges in schema tillwright
  grant all on tables to service_role;
alter default privileges in schema tillwright
  grant all on sequences to service_role;

-- Row-level security ------------------------------------------------------
-- Orders, guest details, invoice numbers and stock are written only by the
-- server with the service role key, which bypasses these policies. The
-- policies below cover what the browser does with a signed-in session.

alter table tillwright.products        enable row level security;
alter table tillwright.transactions    enable row level security;
alter table tillwright.profiles        enable row level security;
alter table tillwright.guest_profiles  enable row level security;

-- Products: anyone reads, only admins write.
drop policy if exists "products are public" on tillwright.products;
create policy "products are public" on tillwright.products
  for select using (true);
drop policy if exists "admins insert products" on tillwright.products;
create policy "admins insert products" on tillwright.products
  for insert to authenticated with check (tillwright.is_admin());
drop policy if exists "admins update products" on tillwright.products;
create policy "admins update products" on tillwright.products
  for update to authenticated using (tillwright.is_admin()) with check (tillwright.is_admin());

-- Transactions: customers see only their own orders, admins see and update
-- all. Orders are placed by the server, so the browser can't insert them.
drop policy if exists "anyone places an order" on tillwright.transactions;
drop policy if exists "customers read own orders" on tillwright.transactions;
create policy "customers read own orders" on tillwright.transactions
  for select to authenticated
  using (email = auth.jwt() ->> 'email' or tillwright.is_admin());
drop policy if exists "admins update orders" on tillwright.transactions;
create policy "admins update orders" on tillwright.transactions
  for update to authenticated using (tillwright.is_admin()) with check (tillwright.is_admin());

-- Profiles: users read their own row. Roles are changed only from the SQL editor.
drop policy if exists "read own profile" on tillwright.profiles;
create policy "read own profile" on tillwright.profiles
  for select to authenticated using (email = auth.jwt() ->> 'email');

-- Guest profiles: written by the server at checkout, read by admins.
drop policy if exists "anyone adds guest details" on tillwright.guest_profiles;
drop policy if exists "admins read guest details" on tillwright.guest_profiles;
create policy "admins read guest details" on tillwright.guest_profiles
  for select to authenticated using (tillwright.is_admin());

-- Storage ------------------------------------------------------------------
-- One public bucket for this app. Product images live under products/.
-- Public URLs work for everyone; admins list and upload. Policy names on
-- storage.objects are shared by every app in the project, hence the prefix.

insert into storage.buckets (id, name, public)
values ('tillwright', 'tillwright', true)
on conflict (id) do nothing;

drop policy if exists "tillwright: admins list product images" on storage.objects;
create policy "tillwright: admins list product images" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'tillwright'
    and (storage.foldername(name))[1] = 'products'
    and tillwright.is_admin()
  );
drop policy if exists "tillwright: admins upload product images" on storage.objects;
create policy "tillwright: admins upload product images" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'tillwright'
    and (storage.foldername(name))[1] = 'products'
    and tillwright.is_admin()
  );

commit;

-- Make the new tables visible to the Supabase API straight away.
notify pgrst, 'reload schema';
