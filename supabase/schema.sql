-- Tillwright database schema.
--
-- Safe to run more than once: it creates what is missing and replaces
-- functions, triggers and policies. It never drops tables or data.
--
-- Apply it either way:
--   - paste it into the Supabase SQL Editor and run it, or
--   - set SUPABASE_DB_URL in .env.local and run `npm run seed`.
--
-- Column types are inferred from what the app reads and writes. See
-- "Database schema" in README.md, including the RLS caveats.

begin;

-- Tables ------------------------------------------------------------------

create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text not null,
  category    text,
  description text,
  image_url   text,
  purchase    numeric,
  mrp         numeric,
  pretax      numeric,
  tax         numeric,
  price       numeric not null,
  inventory   integer default 0
);
-- Projects created before descriptions were added.
alter table public.products add column if not exists description text;

create table if not exists public.transactions (
  id               bigint generated by default as identity primary key,
  created_at       timestamptz not null default now(),
  invoice_id       integer unique,
  transaction_id   text not null,
  razorpay_id      text,
  name             text,
  email            text,
  phone            text,
  address          text,
  payment_status   text not null,
  delivery_status  text not null default 'pending',
  amount           numeric not null,
  products         jsonb not null default '[]'::jsonb
);
create index if not exists transactions_transaction_id_idx on public.transactions (transaction_id);
create index if not exists transactions_email_idx on public.transactions (email);

-- id is not used by the code; it ties each profile to its auth user.
create table if not exists public.profiles (
  id     uuid primary key references auth.users (id) on delete cascade,
  email  text not null unique,
  role   text not null default 'customer'
);

create table if not exists public.guest_profiles (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text,
  email       text,
  phone       text,
  address     text,
  role        text default 'guest'
);

-- Create a profile row for every new sign-up (not in the app code).
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email) values (new.id, new.email)
  on conflict (email) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Admin helper, mirroring the app's check (profiles.role = 'admin' by email).
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.profiles
    where email = auth.jwt() ->> 'email' and role = 'admin'
  );
$$;

-- Row-level security ------------------------------------------------------

alter table public.products        enable row level security;
alter table public.transactions    enable row level security;
alter table public.profiles        enable row level security;
alter table public.guest_profiles  enable row level security;

-- Products: anyone reads, only admins write.
drop policy if exists "products are public" on public.products;
create policy "products are public" on public.products
  for select using (true);
drop policy if exists "admins insert products" on public.products;
create policy "admins insert products" on public.products
  for insert to authenticated with check (public.is_admin());
drop policy if exists "admins update products" on public.products;
create policy "admins update products" on public.products
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- Transactions: customers see only their own orders, admins see and update all.
drop policy if exists "anyone places an order" on public.transactions;
create policy "anyone places an order" on public.transactions
  for insert to anon, authenticated with check (true);
drop policy if exists "customers read own orders" on public.transactions;
create policy "customers read own orders" on public.transactions
  for select to authenticated
  using (email = auth.jwt() ->> 'email' or public.is_admin());
drop policy if exists "admins update orders" on public.transactions;
create policy "admins update orders" on public.transactions
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- Profiles: users read their own row. Roles are changed only from the SQL editor.
drop policy if exists "read own profile" on public.profiles;
create policy "read own profile" on public.profiles
  for select to authenticated using (email = auth.jwt() ->> 'email');

-- Guest profiles: anyone inserts, only admins read.
drop policy if exists "anyone adds guest details" on public.guest_profiles;
create policy "anyone adds guest details" on public.guest_profiles
  for insert to anon, authenticated with check (true);
drop policy if exists "admins read guest details" on public.guest_profiles;
create policy "admins read guest details" on public.guest_profiles
  for select to authenticated using (public.is_admin());

-- Storage: public reads, admin-only uploads to productImages.
drop policy if exists "admins upload product images" on storage.objects;
create policy "admins upload product images" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'productImages' and public.is_admin());

commit;

-- Make the new tables visible to the Supabase API straight away.
notify pgrst, 'reload schema';
